function createHourlyForecast(
  hours: readonly { readonly hour: string; readonly aqi: number; readonly pm25: number; readonly pm10: number }[]
): ForecastHour[] {
  return hours.map((h) => ({
    time: h.hour,
    aqi: h.aqi,
    pm25: h.pm25,
    pm10: h.pm10,
  }));
}

